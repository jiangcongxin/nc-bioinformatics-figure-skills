test_that("tables reject invalid values before plotting", {
  good <- data.frame(x = c(1, 2), y = c(2, 3), cell_type = c("B", "T"))
  expect_error(plot_embedding_panel(list()), "data frame")
  expect_error(plot_embedding_panel(good[FALSE, ]), "at least one row")
  bad <- good; bad$x[1] <- Inf
  expect_error(plot_embedding_panel(bad), "finite numeric")
  bad <- good; bad$x <- as.character(bad$x)
  expect_error(plot_embedding_panel(bad), "finite numeric")
  bad <- good; bad$cell_type[1] <- " "
  expect_error(plot_embedding_panel(bad), "blank")
  expect_error(plot_embedding_panel(good, alpha = 2), "alpha")
  expect_error(plot_embedding_panel(good, category_order = "B"), "category_order")
  p <- plot_embedding_panel(good, label = TRUE, category_order = c("T", "B"))
  expect_identical(levels(p$data$cell_type), c("T", "B"))
  expect_no_error(ggplot2::ggplotGrob(p))
})

